/**
 * Reads Recruitment tab → src/game/recruitmentData.ts
 * Run: node scripts/build-recruitment-data.mjs
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as XLSXNS from "xlsx";

const XLSX = XLSXNS.default ?? XLSXNS;
const __dirname = dirname(fileURLToPath(import.meta.url));

const workbookPath = join(__dirname, "..", "20260731 Corp Idle Working.xlsx");
const outTs = join(__dirname, "..", "src", "game", "recruitmentData.ts");

const TYPE_TO_ID = {
  "Resource Farming": "farming",
  "Protection / Defense": "defense",
  "Intel / Scouting": "intel",
  "Support Units": "support",
};

function slugify(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_|_$/g, "");
}

function parseFlatCost(text) {
  const cost = {};
  const re =
    /\$?\s*([\d,.]+)\s*(cash|\$|sup|con|connection|rep|grep|gov rep|gov reputation|md|mood)/gi;
  let m;
  while ((m = re.exec(text)) !== null) {
    const amount = parseFloat(m[1].replace(/,/g, ""));
    const token = m[2].toLowerCase();
    if (token === "$" || token === "cash") cost.cash = amount;
    else if (token === "sup") cost.supply = amount;
    else if (token === "con" || token === "connection") cost.connection = amount;
    else if (token === "rep") cost.reputation = amount;
    else if (token.startsWith("gov")) cost.govReputation = amount;
    else if (token === "md" || token === "mood") cost.mood = amount;
  }
  return cost;
}

if (!existsSync(workbookPath)) {
  console.error("Workbook not found:", workbookPath);
  process.exit(1);
}

const wb = XLSX.read(readFileSync(workbookPath), { type: "buffer" });
const rows = XLSX.utils.sheet_to_json(wb.Sheets.Recruitment, {
  header: 1,
  defval: "",
});

const units = [];
for (const r of rows) {
  const name = String(r[0] ?? "").trim();
  const typeLabel = String(r[1] ?? "").trim();
  const flatCost = String(r[2] ?? "").trim();
  const tier = Number(r[3]);
  if (!name || name === "Note" || !TYPE_TO_ID[typeLabel] || !tier) continue;

  units.push({
    id: slugify(name),
    name,
    category: TYPE_TO_ID[typeLabel],
    tier,
    cost: parseFlatCost(flatCost),
    detail: String(r[6] ?? "").trim(),
    proposedRole: String(r[7] ?? "").trim(),
  });
}

const tier1ByCategory = {};
for (const u of units) {
  if (u.tier === 1 && !tier1ByCategory[u.category]) {
    tier1ByCategory[u.category] = u;
  }
}

const body = `/** Auto-generated by scripts/build-recruitment-data.mjs — do not edit. */

import type { ContractorCategoryId, ResourceCost, UnitId } from "./types";

export interface RecruitmentUnitDefinition {
  id: UnitId;
  name: string;
  category: ContractorCategoryId;
  tier: number;
  cost: ResourceCost;
  detail: string;
  proposedRole: string;
}

export const RECRUITMENT_UNITS: RecruitmentUnitDefinition[] = ${JSON.stringify(units, null, 2)};

export const UNIT_IDS: UnitId[] = RECRUITMENT_UNITS.map((u) => u.id);

export const DEFAULT_TIER1_UNIT: Record<ContractorCategoryId, UnitId> = ${JSON.stringify(
  {
    farming: tier1ByCategory.farming?.id ?? "fresh_graduate",
    defense: tier1ByCategory.defense?.id ?? "mall_cop",
    intel: tier1ByCategory.intel?.id ?? "internet_surfer",
    support: tier1ByCategory.support?.id ?? "janitor",
  },
  null,
  2,
)};

/** Tier-1 hire cost per category (legacy helper). */
export const RECRUITMENT_TIER1_COST: Record<ContractorCategoryId, ResourceCost> = ${JSON.stringify(
  {
    farming: tier1ByCategory.farming?.cost ?? { cash: 20, reputation: 1 },
    defense: tier1ByCategory.defense?.cost ?? { cash: 95, supply: 30 },
    intel: tier1ByCategory.intel?.cost ?? { cash: 110, supply: 100, connection: 4 },
    support: tier1ByCategory.support?.cost ?? { cash: 150, supply: 100 },
  },
  null,
  2,
)};

export const RECRUITMENT_TIER1_LABEL: Record<ContractorCategoryId, string> = ${JSON.stringify(
  {
    farming: tier1ByCategory.farming?.name ?? "Fresh Graduate",
    defense: tier1ByCategory.defense?.name ?? "Mall Cop",
    intel: tier1ByCategory.intel?.name ?? "Internet surfer",
    support: tier1ByCategory.support?.name ?? "Janitor",
  },
  null,
  2,
)};
`;

writeFileSync(outTs, body, "utf8");
console.log(`Wrote ${outTs} (${units.length} units)`);
