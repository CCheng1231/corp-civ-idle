/**
 * Gov Program sheets → src/game/govProgramData.ts
 * Run: node scripts/build-gov-program-data.mjs
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as XLSXNS from "xlsx";
import { resolveWorkbookPath } from "./workbook-path.mjs";

const XLSX = XLSXNS.default ?? XLSXNS;
const __dirname = dirname(fileURLToPath(import.meta.url));
const outTs = join(__dirname, "..", "src", "game", "govProgramData.ts");

function num(v, fallback = 0) {
  const n = Number(v);
  return Number.isFinite(n) ? n : fallback;
}

function str(v) {
  return v == null ? "" : String(v).trim();
}

function parseTable(wb, sheetName) {
  const sheet = wb.Sheets[sheetName];
  if (!sheet) return [];
  const rows = XLSX.utils.sheet_to_json(sheet, { header: 1, defval: "" });
  if (rows.length < 2) return [];
  const header = rows[0].map((h) => str(h));
  const out = [];
  for (let i = 1; i < rows.length; i++) {
    const row = rows[i];
    if (!row.some((c) => str(c))) continue;
    const obj = {};
    header.forEach((key, idx) => {
      if (key) obj[key] = row[idx];
    });
    out.push(obj);
  }
  return out;
}

function emitGrowthSteps(rows) {
  return rows
    .map(
      (r) => `  {
    stepId: ${JSON.stringify(str(r.stepId))},
    sortOrder: ${num(r.sortOrder)},
    title: ${JSON.stringify(str(r.title))},
    body: ${JSON.stringify(str(r.body))},
    objectiveType: ${JSON.stringify(str(r.objectiveType))},
    param: ${JSON.stringify(str(r.param))},
    reward: { cash: ${num(r.rewardCash)}, supply: ${num(r.rewardSupply)}, connection: ${num(r.rewardConnection)} },
    autoAdvance: ${str(r.autoAdvance).toUpperCase() === "Y"},
  }`,
    )
    .join(",\n");
}

function emitExecutiveSteps(rows) {
  return rows
    .map(
      (r) => `  {
    stepId: ${JSON.stringify(str(r.stepId))},
    sortOrder: ${num(r.sortOrder)},
    title: ${JSON.stringify(str(r.title))},
    body: ${JSON.stringify(str(r.body))},
    objectiveType: ${JSON.stringify(str(r.objectiveType))},
    param: ${JSON.stringify(str(r.param))},
    reward: { cash: ${num(r.rewardCash)}, supply: ${num(r.rewardSupply)} },
    blocksOtherEngages: ${str(r.blocksOtherEngages).toUpperCase() === "Y"},
  }`,
    )
    .join(",\n");
}

function emitCalendar(rows) {
  return rows
    .map(
      (r) => `  {
    questId: ${JSON.stringify(str(r.questId))},
    weight: ${num(r.weight, 1)},
    title: ${JSON.stringify(str(r.title))},
    objectiveType: ${JSON.stringify(str(r.objectiveType))},
    param: ${JSON.stringify(str(r.param))},
    reward: { cash: ${num(r.rewardCash)}, supply: ${num(r.rewardSupply)} },
  }`,
    )
    .join(",\n");
}

function emitCharterJob(row) {
  if (!row) {
    return `{
  definitionId: "gov_charter_introduction",
  title: "Regional orientation charter",
  description: "",
  durationSec: 3600,
  cashPerUnitHour: 10,
  unitHoursTotal: 100,
  minCrew: 10,
  requiresTeamLeadSecretary: true,
  instantTeleport: true,
  payoutCashFlat: 300,
  payoutSupplyFlat: 100,
}`;
  }
  return `{
  definitionId: ${JSON.stringify(str(row.definitionId))},
  title: ${JSON.stringify(str(row.title))},
  description: ${JSON.stringify(str(row.description))},
  durationSec: ${num(row.durationSec, 3600)},
  cashPerUnitHour: ${num(row.cashPerUnitHour, 10)},
  unitHoursTotal: ${num(row.unitHoursTotal, 100)},
  minCrew: ${num(row.minCrew, 10)},
  requiresTeamLeadSecretary: ${str(row.requiresTeamLeadSecretary).toUpperCase() === "Y"},
  instantTeleport: ${str(row.instantTeleport).toUpperCase() === "Y"},
  payoutCashFlat: ${num(row.payoutCashFlat)},
  payoutSupplyFlat: ${num(row.payoutSupplyFlat)},
}`;
}

const wb = XLSX.readFile(resolveWorkbookPath());
const growth = parseTable(wb, "Gov Program Growth");
const executive = parseTable(wb, "Gov Program Executive");
const charterRows = parseTable(wb, "Gov Program Charter Job");
const daily = parseTable(wb, "Gov Program Daily");
const weekly = parseTable(wb, "Gov Program Weekly");
const monthly = parseTable(wb, "Gov Program Monthly");

const ts = `/** Generated by scripts/build-gov-program-data.mjs — do not edit. */

export interface GovProgramReward {
  cash: number;
  supply: number;
  connection?: number;
}

export interface GovGrowthStepDefinition {
  stepId: string;
  sortOrder: number;
  title: string;
  body: string;
  objectiveType: string;
  param: string;
  reward: GovProgramReward;
  autoAdvance: boolean;
}

export interface GovExecutiveStepDefinition {
  stepId: string;
  sortOrder: number;
  title: string;
  body: string;
  objectiveType: string;
  param: string;
  reward: { cash: number; supply: number };
  blocksOtherEngages: boolean;
}

export interface GovCalendarQuestDefinition {
  questId: string;
  weight: number;
  title: string;
  objectiveType: string;
  param: string;
  reward: { cash: number; supply: number };
}

export interface GovCharterJobDefinition {
  definitionId: string;
  title: string;
  description: string;
  durationSec: number;
  cashPerUnitHour: number;
  unitHoursTotal: number;
  minCrew: number;
  requiresTeamLeadSecretary: boolean;
  instantTeleport: boolean;
  payoutCashFlat: number;
  payoutSupplyFlat: number;
}

export const GOV_RECRUIT_UNLOCK_COUNT = 10;

export const GOV_GROWTH_STEPS: GovGrowthStepDefinition[] = [
${emitGrowthSteps(growth)}
];

export const GOV_EXECUTIVE_STEPS: GovExecutiveStepDefinition[] = [
${emitExecutiveSteps(executive)}
];

export const GOV_CHARTER_JOB: GovCharterJobDefinition = ${emitCharterJob(charterRows[0])};

export const GOV_DAILY_QUESTS: GovCalendarQuestDefinition[] = [
${emitCalendar(daily)}
];

export const GOV_WEEKLY_QUESTS: GovCalendarQuestDefinition[] = [
${emitCalendar(weekly)}
];

export const GOV_MONTHLY_QUESTS: GovCalendarQuestDefinition[] = [
${emitCalendar(monthly)}
];
`;

writeFileSync(outTs, ts, "utf8");
console.log(`Wrote gov program data → ${outTs}`);
